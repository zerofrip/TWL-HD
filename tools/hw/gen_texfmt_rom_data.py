"""Generate arm9v2/source/texfmt_data.h for the TEXFMT=1 DS ROM.

The ROM reproduces the eight-quad grid of tools/gen_tex_format_frames.py on
real DS hardware.  This tool places the textures of that generator in three
VRAM images (texture slot 0, texture slot 1, texture palette) and writes them,
with the per-quad TEXIMAGE_PARAM / PLTT_BASE words and the clip-space corners,
as a C header.  The header is committed; tools/test_hw_texfmt_data.py checks
that it equals this tool's output and that every texture decoded back out of
the images equals the generator's own expectation.

Stdlib only.  Nothing here contacts a console or a network address.
"""

import os
import struct
import sys

TOOLS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if TOOLS_DIR not in sys.path:
    sys.path.insert(0, TOOLS_DIR)

import gen_tex_format_frames as gen  # noqa: E402

# Texel byte offsets inside texture slot 0 (TEXIMAGE_PARAM offset = byte >> 3).
TEXEL_OFFSETS = (0x000, 0x100, 0x200, 0x300, 0x400, 0x500, 0x600, 0x700)
# Palette byte offsets inside the texture palette; None = no palette.
PALETTE_OFFSETS = (0x00, 0x40, 0x50, 0x80, 0x280, 0x2A0, None, 0x50)

SLOT0_BYTES = 0x800
SLOT1_BYTES = 0x208
PALETTE_BYTES = 0x2B0

HEADER_PATH = os.path.join(os.path.dirname(TOOLS_DIR), "arm9v2", "source",
                           "texfmt_data.h")


def _pltt_base(fmt, palette_offset):
    """PLTT_BASE word: byte offset >> 3 for I2 (format 2), else >> 4."""
    if palette_offset is None:
        return 0
    return palette_offset >> (3 if fmt == 2 else 4)


def layout():
    """Return (slot0, slot1, palette, quads) for the committed header."""
    slot0 = bytearray(SLOT0_BYTES)
    slot1 = bytearray(SLOT1_BYTES)
    palette = bytearray(PALETTE_BYTES)
    quads = []
    for spec, t_off, p_off in zip(gen.QUAD_SPECS, TEXEL_OFFSETS,
                                  PALETTE_OFFSETS):
        slot0[t_off:t_off + len(spec["texel"])] = spec["texel"]
        if spec["index"]:
            # Compressed 4x4: index data in slot 1 at (texel offset / 2).
            i_off = t_off >> 1
            slot1[i_off:i_off + len(spec["index"])] = spec["index"]
        if spec["palette"]:
            palette[p_off:p_off + len(spec["palette"])] = spec["palette"]
        quads.append({
            "param": spec["param"] | (t_off >> 3),
            "pltt": _pltt_base(spec["format"], p_off),
            "width": spec["width"],
            "height": spec["height"],
            "corners": spec["corners"],
        })
    return bytes(slot0), bytes(slot1), bytes(palette), quads


def _array(name, data):
    words = struct.unpack("<%dH" % (len(data) // 2), data)
    lines = ["static const uint16_t %s[%d] __attribute__((aligned(4))) = {"
             % (name, len(words))]
    for start in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%04X" % w
                                         for w in words[start:start + 8]) +
                     ",")
    lines.append("};")
    return "\n".join(lines)


def header_text():
    slot0, slot1, palette, quads = layout()
    out = ["// SPDX-License-Identifier: Apache-2.0",
           "// Generated by tools/hw/gen_texfmt_rom_data.py; do not edit.",
           "// VRAM images and per-quad words for the TEXFMT=1 ROM.",
           "#pragma once",
           "",
           "#include <stdint.h>",
           "",
           _array("texfmt_slot0", slot0), "",
           _array("texfmt_slot1", slot1), "",
           _array("texfmt_palette", palette), "",
           "struct TexfmtQuad {",
           "    uint32_t param;     /* TEXIMAGE_PARAM incl. texel offset */",
           "    uint32_t pltt;      /* PLTT_BASE */",
           "    int16_t s_max;      /* width * 16 (12.4) */",
           "    int16_t t_max;      /* height * 16 (12.4) */",
           "    int16_t corners[4][2];  /* clip * 4096, TL TR BR BL */",
           "};",
           "",
           "static const struct TexfmtQuad texfmt_quads[8] = {"]
    for quad in quads:
        c = quad["corners"]
        out.append("    {0x%08XU, %d, %d, %d, {{%d, %d}, {%d, %d}, {%d, %d},"
                   " {%d, %d}}},"
                   % ((quad["param"], quad["pltt"], quad["width"] * 16,
                       quad["height"] * 16) +
                      tuple(v for corner in c for v in corner)))
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv=None):
    text = header_text()
    path = argv[0] if argv else HEADER_PATH
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
