"""Generate arm9v2/source/texbeh_data.h for the TEXBEH=1 DS ROM (EQ-4zl).

The ROM reproduces the eight-quad behaviour frame of
tools/gen_tex_behaviour_frames.py (texture alpha, KeyColor0, repeat, clamp,
mirrored repeat, flip-only) on real DS hardware.  This tool places the textures
in the texture slot-0 and palette VRAM images and writes them, with the per-quad
TEXIMAGE_PARAM / PLTT_BASE words, texcoords and clip corners, as a C header.
tools/test_hw_texbeh_data.py checks the header against this tool and decodes
every texture back out of the images.

Stdlib only.  Nothing here contacts a console or a network address.
"""

import os
import struct
import sys

TOOLS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if TOOLS_DIR not in sys.path:
    sys.path.insert(0, TOOLS_DIR)

import gen_tex_behaviour_frames as beh  # noqa: E402

TEXEL_STRIDE = 0x80
SLOT0_BYTES = 8 * TEXEL_STRIDE
# Palette byte offsets: A3I5 (64 B), A5I3 (16 B), I4 shared by quads 2 and 3
# (32 B); the 16bpp wrap quads have no palette.
PALETTE_OFFSETS = (0x00, 0x40, 0x50, 0x50, None, None, None, None)
PALETTE_BYTES = 0x70

HEADER_PATH = os.path.join(os.path.dirname(TOOLS_DIR), "arm9v2", "source",
                           "texbeh_data.h")


def layout():
    slot0 = bytearray(SLOT0_BYTES)
    palette = bytearray(PALETTE_BYTES)
    quads = []
    for index, spec in enumerate(beh.QUAD_SPECS):
        t_off = index * TEXEL_STRIDE
        slot0[t_off:t_off + len(spec["texel"])] = spec["texel"]
        p_off = PALETTE_OFFSETS[index]
        if spec["palette"]:
            palette[p_off:p_off + len(spec["palette"])] = spec["palette"]
        coords = []
        for u, v in spec["texcoords"]:
            coords.append((int(u * spec["width"] * 16.0),
                           int(v * spec["height"] * 16.0)))
        quads.append({
            "param": spec["param"] | (t_off >> 3),
            "pltt": 0 if p_off is None else p_off >> 4,
            "texcoords": coords,
            "corners": spec["corners"],
        })
    return bytes(slot0), bytes(palette), quads


def _array(name, data):
    words = struct.unpack("<%dH" % (len(data) // 2), data)
    lines = ["static const uint16_t %s[%d] __attribute__((aligned(4))) = {"
             % (name, len(words))]
    for start in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%04X" % w
                                         for w in words[start:start + 8]) +
                     ",")
    lines.append("};")
    return "\n".join(lines)


def header_text():
    slot0, palette, quads = layout()
    out = ["// SPDX-License-Identifier: Apache-2.0",
           "// Generated by tools/hw/gen_texbeh_rom_data.py; do not edit.",
           "// VRAM images and per-quad words for the TEXBEH=1 ROM.",
           "#pragma once",
           "",
           "#include <stdint.h>",
           "",
           _array("texbeh_slot0", slot0), "",
           _array("texbeh_palette", palette), "",
           "struct TexbehQuad {",
           "    uint32_t param;      /* TEXIMAGE_PARAM incl. texel offset */",
           "    uint32_t pltt;       /* PLTT_BASE */",
           "    int16_t texcoords[6][2];  /* s, t in 12.4, triangle order */",
           "    int16_t corners[4][2];    /* clip * 4096, TL TR BR BL */",
           "};",
           "",
           "static const struct TexbehQuad texbeh_quads[8] = {"]
    for quad in quads:
        tc = ", ".join("{%d, %d}" % (s, t) for s, t in quad["texcoords"])
        c = quad["corners"]
        out.append("    {0x%08XU, %d, {%s}, {{%d, %d}, {%d, %d}, {%d, %d},"
                   " {%d, %d}}},"
                   % ((quad["param"], quad["pltt"], tc) +
                      tuple(v for corner in c for v in corner)))
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv=None):
    path = argv[0] if argv else HEADER_PATH
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(header_text())
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
