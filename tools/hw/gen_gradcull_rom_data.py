"""Generate arm9v2/source/gradcull_data.h for the GRAD=1 and CULL=1 DS ROMs.

GRAD (EQ-4zm): two Gouraud triangles with different vertex colours; the
hardware interior is compared with the barycentric blend of the corner colours
(tools/hw/measure_grad.py).

CULL (EQ-4zn): eight flat white quads on the 4x2 grid of
tools/gen_tex_format_frames.py, windings TL-TR-BR-BL and TL-BL-BR-TR crossed
with POLYGON_ATTR bits 6-7 = 1, 2, 3, 0; which of them appear on screen shows
which winding the DS treats as the front face and what each attribute value
does (tools/hw/measure_cull.py).

Stdlib only.  Nothing here contacts a console or a network address.
"""

import os
import sys

TOOLS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if TOOLS_DIR not in sys.path:
    sys.path.insert(0, TOOLS_DIR)

import gen_tex_format_frames as gen  # noqa: E402

# Clip units (x4096).  Inside the +-3994 pillar-box limit used elsewhere.
GRAD_TRIANGLES = (
    {"vertices": ((-3700, 3500), (-300, 3500), (-2000, -3500)),
     "colours": ((31, 0, 0), (0, 31, 0), (0, 0, 31))},
    {"vertices": ((300, 3500), (3700, 3500), (2000, -3500)),
     "colours": ((31, 31, 0), (0, 31, 31), (31, 0, 31))},
)

# (winding name, POLYGON_ATTR bits 6-7), one per grid cell in order.
CULL_CASES = (
    ("TL-TR-BR-BL", 1), ("TL-TR-BR-BL", 2), ("TL-TR-BR-BL", 3),
    ("TL-TR-BR-BL", 0),
    ("TL-BL-BR-TR", 1), ("TL-BL-BR-TR", 2), ("TL-BL-BR-TR", 3),
    ("TL-BL-BR-TR", 0),
)

HEADER_PATH = os.path.join(os.path.dirname(TOOLS_DIR), "arm9v2", "source",
                           "gradcull_data.h")


def cull_corners(index):
    """Corner order of the cull quad `index` (TL TR BR BL source order)."""
    tl, tr, br, bl = gen.QUAD_SPECS[index]["corners"]
    if CULL_CASES[index][0] == "TL-TR-BR-BL":
        return (tl, tr, br, bl)
    return (tl, bl, br, tr)


def header_text():
    out = ["// SPDX-License-Identifier: Apache-2.0",
           "// Generated by tools/hw/gen_gradcull_rom_data.py; do not edit.",
           "// Triangle / quad data for the GRAD=1 and CULL=1 ROMs.",
           "#pragma once",
           "",
           "#include <stdint.h>",
           "",
           "struct GradTriangle {",
           "    int16_t vertices[3][2];   /* clip * 4096 */",
           "    uint16_t colours[3];      /* RGB555 */",
           "};",
           "",
           "static const struct GradTriangle grad_triangles[2] = {"]
    for tri in GRAD_TRIANGLES:
        v = tri["vertices"]
        c = ["0x%04X" % (r | (g << 5) | (b << 10)) for r, g, b in
             tri["colours"]]
        out.append("    {{{%d, %d}, {%d, %d}, {%d, %d}}, {%s}},"
                   % (v[0] + v[1] + v[2] + (", ".join(c),)))
    out += ["};",
            "",
            "struct CullQuad {",
            "    uint32_t attr_bits;       /* POLYGON_ATTR bits 6-7, in place */",
            "    int16_t corners[4][2];    /* clip * 4096, draw order */",
            "};",
            "",
            "static const struct CullQuad cull_quads[8] = {"]
    for index, (_name, bits) in enumerate(CULL_CASES):
        c = cull_corners(index)
        out.append("    {0x%02XU, {{%d, %d}, {%d, %d}, {%d, %d}, {%d, %d}}},"
                   % ((bits << 6,) + tuple(v for corner in c for v in corner)))
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv=None):
    path = argv[0] if argv else HEADER_PATH
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(header_text())
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
