"""Generate arm9v2/source/texmod_data.h for the TEXMOD=1 DS ROM (EQ-4zk).

Eight flat quads on the grid of tools/gen_tex_format_frames.py.  Each quad has
one solid 8x8 16bpp texture and one flat vertex colour, so the output of the
DS MODULATE texture mode is one colour per quad: three (texel, vertex)
channel pairs per quad, 24 pairs in total.  The header is committed;
tools/test_hw_texmod.py checks it against this tool and decodes the textures
back out of the VRAM image.

Stdlib only.  Nothing here contacts a console or a network address.
"""

import os
import struct
import sys

TOOLS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if TOOLS_DIR not in sys.path:
    sys.path.insert(0, TOOLS_DIR)

import gen_tex_format_frames as gen  # noqa: E402

# Per quad: ((texel R, G, B), (vertex R, G, B)), 5-bit levels.
PAIRS = (
    ((31, 31, 31), (31, 16, 8)),
    ((16, 24, 8), (16, 12, 24)),
    ((20, 12, 5), (20, 28, 31)),
    ((31, 16, 28), (3, 8, 28)),
    ((10, 3, 18), (10, 31, 27)),
    ((25, 14, 22), (9, 22, 14)),
    ((7, 30, 2), (7, 30, 2)),
    ((27, 9, 13), (5, 27, 19)),
)

TEXEL_STRIDE = 0x80
SLOT0_BYTES = 8 * TEXEL_STRIDE
HEADER_PATH = os.path.join(os.path.dirname(TOOLS_DIR), "arm9v2", "source",
                           "texmod_data.h")


def rgb555(rgb, opaque=False):
    r, g, b = rgb
    return r | (g << 5) | (b << 10) | (0x8000 if opaque else 0)


def layout():
    """Return (slot0 image, quads)."""
    slot0 = bytearray(SLOT0_BYTES)
    quads = []
    for index, (texel, vertex) in enumerate(PAIRS):
        offset = index * TEXEL_STRIDE
        word = struct.pack("<H", rgb555(texel, opaque=True))
        slot0[offset:offset + TEXEL_STRIDE] = word * (TEXEL_STRIDE // 2)
        spec = gen.QUAD_SPECS[index]
        quads.append({
            "param": (7 << 26) | (offset >> 3),  # 16bpp, 8x8
            "colour": rgb555(vertex),
            "corners": spec["corners"],
        })
    return bytes(slot0), quads


def header_text():
    slot0, quads = layout()
    words = struct.unpack("<%dH" % (len(slot0) // 2), slot0)
    out = ["// SPDX-License-Identifier: Apache-2.0",
           "// Generated by tools/hw/gen_texmod_rom_data.py; do not edit.",
           "// VRAM image and per-quad words for the TEXMOD=1 ROM.",
           "#pragma once",
           "",
           "#include <stdint.h>",
           "",
           "static const uint16_t texmod_slot0[%d] "
           "__attribute__((aligned(4))) = {" % len(words)]
    for start in range(0, len(words), 8):
        out.append("    " + ", ".join("0x%04X" % w
                                      for w in words[start:start + 8]) + ",")
    out += ["};",
            "",
            "struct TexmodQuad {",
            "    uint32_t param;      /* TEXIMAGE_PARAM incl. texel offset */",
            "    uint16_t colour;     /* flat vertex colour, RGB555 */",
            "    int16_t corners[4][2];  /* clip * 4096, TL TR BR BL */",
            "};",
            "",
            "static const struct TexmodQuad texmod_quads[8] = {"]
    for quad in quads:
        c = quad["corners"]
        out.append("    {0x%08XU, 0x%04X, {{%d, %d}, {%d, %d}, {%d, %d},"
                   " {%d, %d}}},"
                   % ((quad["param"], quad["colour"]) +
                      tuple(v for corner in c for v in corner)))
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv=None):
    path = argv[0] if argv else HEADER_PATH
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(header_text())
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
